# Tests for libs/encryption.py, the decryption of files uploaded by the Android and iOS apps.
#
# File format, as written by the apps:
#   line 1: the AES key, base64 encoded, then encrypted with textbook RSA (no padding scheme) using
#           the participant's public key, then base64 encoded again.
#   lines 2+: "<base64 iv>:<base64 AES-CBC ciphertext>", one line of plaintext per line of file.
#
# Test classes are separate so that `--parallel` can run them concurrently. None of them touch S3,
# the RSA key is always passed in (or Participant.get_private_key is patched).


# One key pair for the whole module, RSA key generation is the slowest part of these tests.
RSA_KEY = RSA.generate(ASYMMETRIC_KEY_LENGTH)
OTHER_RSA_KEY = RSA.generate(ASYMMETRIC_KEY_LENGTH)

FAKE_DSN = "https://encryption@o0.ingest.sentry.io/3"


def textbook_rsa_encrypt(public_key: RSA.RsaKey, plaintext: bytes) -> bytes:
    """ The apps encrypt the AES key with raw RSA, no padding. This is the inverse of
    DeviceDataDecryptor.rsa_decrypt. """
    ciphertext_int = pow(int.from_bytes(plaintext, "big"), public_key.e, public_key.n)
    return ciphertext_int.to_bytes(public_key.size_in_bytes(), "big")


def pkcs5_pad(data: bytes) -> bytes:
    # always adds 1-16 bytes, a full block of padding when the data is already aligned.
    padding_length = 16 - (len(data) % 16)
    return data + bytes([padding_length]) * padding_length


class DeviceEncryptor:
    """ Encrypts data the way the apps do, so tests can build real uploaded files. """
    
    def __init__(self, public_key: RSA.RsaKey = RSA_KEY, aes_key: bytes | None = None):
        self.public_key = public_key
        self.aes_key = os.urandom(16) if aes_key is None else aes_key
    
    def key_line(self) -> bytes:
        return key_line_from_rsa_plaintext(encode_base64(self.aes_key), self.public_key)
    
    def encrypt_line(self, plaintext: bytes, iv: bytes | None = None) -> bytes:
        iv = os.urandom(16) if iv is None else iv
        ciphertext = AES.new(self.aes_key, AES.MODE_CBC, iv=iv).encrypt(pkcs5_pad(plaintext))
        return encode_base64(iv) + b":" + encode_base64(ciphertext)
    
    def encrypt_file(self, *plaintext_lines: bytes) -> bytes:
        return b"\n".join([self.key_line()] + [self.encrypt_line(line) for line in plaintext_lines])


def key_line_from_rsa_plaintext(rsa_plaintext: bytes, public_key: RSA.RsaKey = RSA_KEY) -> bytes:
    """ Builds a key line that RSA-decrypts to exactly `rsa_plaintext`. Lets tests control what the
    server sees after RSA decryption, which is where the key handling (and leak risk) starts. """
    return encode_base64(textbook_rsa_encrypt(public_key, rsa_plaintext))


