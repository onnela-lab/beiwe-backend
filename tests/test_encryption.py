class TestDecryptionRoundTrip(EncryptionTestCase):
    """ Data encrypted the way the apps encrypt it must come back out byte-for-byte. Everything else
    in this file is about failure cases, these tests establish that the success case is correct. """
    
    def test_single_line(self):
        decryptor = self.decrypt(DeviceEncryptor().encrypt_file(b"hello world"))
        self.assertEqual(decryptor.decrypted_file, b"hello world")
    
    def test_multiple_lines_keep_order_and_are_newline_joined(self):
        # Uploaded files are csvs, line order is the row order and must be preserved.
        lines = [b"timestamp,x,y,z", b"1,2,3,4", b"5,6,7,8", b"9,10,11,12"]
        decryptor = self.decrypt(DeviceEncryptor().encrypt_file(*lines))
        self.assertEqual(decryptor.decrypted_file, b"\n".join(lines))
    
    def test_every_padding_length(self):
        # PKCS5 padding always adds between 1 and 16 bytes, and the decryptor strips it by reading
        # the last byte. Lengths 0-33 cover every padding length including a full padding block, an
        # off-by-one here would silently truncate or corrupt the end of every line.
        encryptor = DeviceEncryptor()
        for length in range(34):
            with self.subTest(length=length):
                plaintext = bytes(range(65, 65 + length))
                decryptor = self.decrypt(encryptor.encrypt_file(plaintext))
                self.assertEqual(decryptor.decrypted_file, plaintext)
    
    def test_binary_plaintext(self):
        # Nothing in the decryption path should assume text, some data streams are not ascii.
        plaintext = bytes(range(1, 256)).replace(b"\n", b"")
        decryptor = self.decrypt(DeviceEncryptor().encrypt_file(plaintext))
        self.assertEqual(decryptor.decrypted_file, plaintext)
    
    def test_blank_lines_are_ignored(self):
        # Blank lines are dropped by split_file before decryption, they are not line errors.
        encryptor = DeviceEncryptor()
        file_data = b"\n".join(
            [encryptor.key_line(), b"", encryptor.encrypt_line(b"a"), b"", b"", encryptor.encrypt_line(b"b"), b""]
        )
        decryptor = self.decrypt(file_data)
        self.assertEqual(decryptor.decrypted_file, b"a\nb")
        self.assertEqual(decryptor.error_count, 0)
    
    def test_key_only_file_decrypts_to_empty(self):
        # A file with a valid key and no data is not an error here, the upload endpoint checks for
        # an empty decrypted_file and handles it separately.
        decryptor = self.decrypt(DeviceEncryptor().key_line())
        self.assertEqual(decryptor.decrypted_file, b"")
    
    def test_unaligned_trailing_ciphertext_bytes_are_dropped(self):
        # CBC ciphertext must be a multiple of 16 bytes. Interrupted writes can leave extra bytes on
        # the end of a line, the decryptor drops them and decrypts the aligned part rather than
        # failing the line.
        encryptor = DeviceEncryptor()
        iv = os.urandom(16)
        ciphertext = AES.new(encryptor.aes_key, AES.MODE_CBC, iv=iv).encrypt(pkcs5_pad(b"some data"))
        line = encode_base64(iv) + b":" + encode_base64(ciphertext + b"xyz")
        decryptor = self.decrypt(encryptor.key_line() + b"\n" + line)
        self.assertEqual(decryptor.decrypted_file, b"some data")
    
    def test_null_bytes_inside_a_data_line_are_tolerated(self):
        # Partial null byte corruption is logged but not rejected (basic_file_validation), and
        # non-strict base64 decoding skips characters outside the alphabet. A line with nulls in it
        # still decrypts. (A file that is entirely null bytes is a different case, see
        # TestFileAndKeyErrors.)
        encryptor = DeviceEncryptor()
        line = encryptor.encrypt_line(b"some data")
        line = line[:5] + b"\x00\x00" + line[5:]
        decryptor = self.decrypt(encryptor.key_line() + b"\n" + line)
        self.assertEqual(decryptor.decrypted_file, b"some data")
    
    def test_uses_participant_private_key_when_no_key_is_passed(self):
        # The upload endpoint does not pass a key, the decryptor must fetch the participant's key.
        file_data = DeviceEncryptor().encrypt_file(b"hello")
        with patch.object(Participant, "get_private_key", return_value=RSA_KEY) as get_private_key:
            decryptor = DeviceDataDecryptor("some/file.csv", file_data, self.default_participant)
        get_private_key.assert_called_once()
        self.assertEqual(decryptor.decrypted_file, b"hello")
    
    def test_clean_decryption_creates_no_error_metadata(self):
        # EncryptionErrorMetadata rows are for debugging failed lines, a clean file should not
        # create one.
        self.decrypt(DeviceEncryptor().encrypt_file(b"a", b"b"))
        self.assertFalse(EncryptionErrorMetadata.objects.exists())


class TestFileAndKeyErrors(EncryptionTestCase):
    """ Whole-file failures. These decide what the upload endpoint tells the device:
    RemoteDeleteFileScenario means "return 200 so the device deletes the file", and any other
    exception (including DecryptionKeyInvalidError) keeps the file as a problem upload and reports
    it to Sentry. Getting the exception type wrong either deletes recoverable data or retains junk. """
    
    def test_empty_file_is_remote_delete(self):
        for file_data in [b"", b"\n", b"\n\n\n"]:
            with self.subTest(file_data=file_data):
                with self.assertRaises(RemoteDeleteFileScenario) as context:
                    self.decrypt(file_data)
                self.assertEqual(str(context.exception), NO_DATA_DECRYPTION_MESSAGE)
    
    # KNOWN BUG: run_decryption calls extract_aes_key before decrypt_device_file (which calls
    # basic_file_validation), so an all-null file fails on its key line with a
    # DecryptionKeyInvalidError and the null byte check never runs. Remove expectedFailure when fixed.
    @unittest.expectedFailure
    @patch("libs.encryption.send_sentry_warning")
    def test_all_null_bytes_is_remote_delete_with_sentry_warning(self, send_sentry_warning):
        # Real-world corruption occasionally produces files of only null bytes. There is nothing to
        # recover, so the device should delete it, but we still want to hear about it.
        with self.assertRaises(RemoteDeleteFileScenario):
            self.decrypt(b"\x00" * 100)
        send_sentry_warning.assert_called_once()
        self.assertEqual(send_sentry_warning.call_args.kwargs["byte_count"], 100)
        self.assertEqual(send_sentry_warning.call_args.kwargs["file_name"], "some/file.csv")
    
    def test_key_line_with_non_base64_characters(self):
        with self.assertRaises(DecryptionKeyInvalidError) as context:
            self.decrypt(b"not!base64\n" + DeviceEncryptor().encrypt_line(b"a"))
        self.assertIn("Key not base64 encoded", str(context.exception))
    
    def test_key_line_with_invalid_base64_length(self):
        with self.assertRaises(DecryptionKeyInvalidError) as context:
            self.decrypt(b"abcde\n" + DeviceEncryptor().encrypt_line(b"a"))
        self.assertIn("Invalid decryption key", str(context.exception))
    
    def test_wrong_rsa_key(self):
        # Decrypting with the wrong private key produces garbage. That garbage has to be caught by
        # the key validation as a DecryptionKeyInvalidError, not decrypt the file into junk data.
        with self.assertRaises(DecryptionKeyInvalidError):
            self.decrypt(DeviceEncryptor().encrypt_file(b"a"), rsa_key=OTHER_RSA_KEY)
    
    def test_aes_key_that_decodes_to_empty(self):
        # An RSA plaintext of zero decodes to an empty key. This must fail on the key, not later as
        # an AES error on every line.
        file_data = key_line_from_rsa_plaintext(b"") + b"\n" + DeviceEncryptor().encrypt_line(b"a")
        with self.assertRaises(DecryptionKeyInvalidError) as context:
            self.decrypt(file_data)
        self.assertEqual(str(context.exception), "Invalid decryption key: TypeError")
    
    def test_aes_key_of_wrong_length(self):
        # AES keys from the apps are 128 bits. Any other length means the key is wrong (historically
        # an RSA leading-zero bug, or the wrong RSA key). AES.new would accept a 24 or 32 byte key,
        # so this check is the only thing that stops decryption with a bad key.
        encryptor = DeviceEncryptor(aes_key=os.urandom(32))
        with self.assertRaises(DecryptionKeyInvalidError) as context:
            self.decrypt(encryptor.encrypt_file(b"a"))
        self.assertEqual(str(context.exception), "Decryption key not 128 bits: 32 bytes")


class TestLineErrors(EncryptionTestCase):
    """ Individual lines can be corrupted (interrupted writes, partial uploads) while the rest of the
    file is fine. Known line errors are recorded and skipped so one bad line does not lose the file,
    unknown errors are raised so they are not silently dropped. Several of these cases are detected
    by matching exception message text from Python or pycryptodome, so these tests also guard
    against library upgrades changing that text. """
    
    # (description, bad line, expected LineEncryptionError)
    BAD_LINES = [
        # "values to unpack" is Python's message for the iv:data split failing.
        ("no colon", encode_base64(os.urandom(16)) + encode_base64(os.urandom(32)), LineEncryptionError.MALFORMED_CONFIG),
        ("two colons", b"YWJj:YWJj:YWJj", LineEncryptionError.MALFORMED_CONFIG),
        ("empty iv", b":" + encode_base64(os.urandom(32)), LineEncryptionError.IV_MISSING),
        ("short iv", encode_base64(os.urandom(8)) + b":" + encode_base64(os.urandom(32)), LineEncryptionError.IV_MISSING),
        # "Incorrect IV length" is pycryptodome's message, a long iv only fails inside AES.new.
        ("long iv", encode_base64(os.urandom(17)) + b":" + encode_base64(os.urandom(32)), LineEncryptionError.IV_BAD_LENGTH),
        ("empty data", encode_base64(os.urandom(16)) + b":", LineEncryptionError.LINE_EMPTY),
        ("data under 16 bytes", encode_base64(os.urandom(16)) + b":" + encode_base64(os.urandom(8)), LineEncryptionError.LINE_EMPTY),
        ("bad base64 length in data", encode_base64(os.urandom(16)) + b":abcde", LineEncryptionError.PADDING_ERROR),
        ("bad base64 length in iv", b"abcde:" + encode_base64(os.urandom(32)), LineEncryptionError.PADDING_ERROR),
    ]
    
    def test_each_known_line_error_is_recorded_and_skipped(self):
        encryptor = DeviceEncryptor()
        for description, bad_line, expected_error in self.BAD_LINES:
            with self.subTest(description):
                file_data = b"\n".join([
                    encryptor.key_line(),
                    encryptor.encrypt_line(b"before"),
                    bad_line,
                    encryptor.encrypt_line(b"after"),
                ])
                decryptor = self.decrypt(file_data)
                self.assertEqual(decryptor.decrypted_file, b"before\nafter")
                self.assertEqual(decryptor.error_types, [expected_error])
                self.assertEqual(decryptor.bad_lines, [bad_line])
                self.assertEqual(decryptor.error_count, 1)
    
    def test_error_metadata_is_stored(self):
        # The EncryptionErrorMetadata row is how we debug line errors after the fact. total_lines
        # counts the key line. The stored lines are ciphertext, which is safe to keep.
        encryptor = DeviceEncryptor()
        bad_line_1 = b"YWJj:YWJj:YWJj"
        bad_line_2 = encode_base64(os.urandom(16)) + b":"
        file_data = b"\n".join([
            encryptor.key_line(),
            encryptor.encrypt_line(b"a"),
            bad_line_1,
            bad_line_2,
            encryptor.encrypt_line(b"b"),
        ])
        self.decrypt(file_data, file_name="some/specific_file.csv")
        
        metadata = EncryptionErrorMetadata.objects.get()
        self.assertEqual(metadata.file_name, "some/specific_file.csv")
        self.assertEqual(metadata.participant_id, self.default_participant.id)
        self.assertEqual(metadata.total_lines, 5)
        self.assertEqual(metadata.number_errors, 2)
        self.assertEqual(
            json.loads(metadata.error_types),
            [LineEncryptionError.MALFORMED_CONFIG, LineEncryptionError.LINE_EMPTY],
        )
        self.assertEqual(json.loads(metadata.error_lines), [str(bad_line_1), str(bad_line_2)])
    
    def test_unknown_line_error_is_raised(self):
        # An error we have not seen before must fail the upload, not be swallowed as a line error.
        # The endpoint then keeps the file as a problem upload and reports it, so we find out.
        with patch.object(DeviceDataDecryptor, "decrypt_device_line", side_effect=ValueError("novel")):
            with self.assertRaises(ValueError):
                self.decrypt(DeviceEncryptor().encrypt_file(b"a"))
        self.assertFalse(EncryptionErrorMetadata.objects.exists())
    
    def test_incorrect_padding_on_non_csv_is_remote_delete(self):
        # Seen on truncated mp4 (audio) uploads, which cannot be recovered, so the device deletes
        # them. Normal data does not reach this branch (decode_base64 raises its own exception
        # types), so the error is injected.
        with patch.object(
            DeviceDataDecryptor, "decrypt_device_line", side_effect=ValueError("Incorrect padding")
        ):
            with self.assertRaises(RemoteDeleteFileScenario):
                self.decrypt(DeviceEncryptor().encrypt_file(b"a"), file_name="some/file.mp4")


class CapturingTransport(Transport):
    """ Records events instead of sending them. """
    events: list[dict] = []
    
    def capture_envelope(self, envelope):
        for item in envelope.items:
            if item.type == "event" and item.payload.json is not None:
                self.events.append(item.payload.json)


class TestDecryptionSentryScrubbing(EncryptionTestCase):
    """ Sentry reports include the local variables of every stack frame in an exception's traceback,
    including frames in the standard library and in chained exceptions. Decryption errors from the
    upload endpoint are reported to Sentry, so key material and decrypted data must not be held in
    local variables Sentry can see. libs/encryption.py keeps them in a dict named `secret`, which the
    SDK's default EventScrubber filters, and libs/rsa.py sanitizes the RsaKey repr.
    
    These tests run real exceptions through a sentry client built with the production options, so
    they fail if the scrubbing stops working for any reason: a code change in encryption.py, a client
    option change in libs/sentry.py, or a Sentry SDK upgrade.
    
    Not tested, by decision: if AES.new raises, the AES key is visible in pycryptodome's frames. The
    key is validated before that point and we want to see a novel malformed key if one gets through.
    (See the comment above AES.new in decrypt_device_line.) """
    
    def setUp(self) -> None:
        CapturingTransport.events = []
        return super().setUp()
    
    def capture(self, file_data: bytes, expected_exception: type[Exception]) -> tuple[dict, str]:
        """ Runs a failing decryption and reports it the way SentryErrorHandler does, returns the
        event and the event serialized to a string for searching. """
        client = sentry_sdk.Client(FAKE_DSN, **{**sentry_client_options(), "transport": CapturingTransport})
        # Not assertRaises, it strips the traceback from the exception, and the traceback is what
        # these tests inspect.
        try:
            self.decrypt(file_data)
        except expected_exception as e:
            with sentry_sdk.new_scope() as scope:
                scope.set_client(client)
                sentry_sdk.capture_exception(e)
        else:
            self.fail(f"{expected_exception.__name__} not raised")
        self.assertEqual(len(CapturingTransport.events), 1)
        event = CapturingTransport.events[0]
        return event, json.dumps(event, default=str)
    
    def get_frame(self, event: dict, function_name: str) -> dict:
        for exception in event["exception"]["values"]:
            for frame in exception["stacktrace"]["frames"]:
                if frame["function"] == function_name:
                    return frame
        self.fail(f"no frame for {function_name}")
    
    def test_rsa_key_repr_is_sanitized(self):
        # The default RsaKey repr prints the private key components. Every frame holding the
        # participant's key (DeviceDataDecryptor.__init__'s `rsa_key`, for one) would leak it.
        self.assertEqual(repr(RSA_KEY), "<SANITIZED RsaKey>")
        self.assertNotIn(str(RSA_KEY.d), repr(RSA_KEY))
        self.assertEqual(repr(RSA_KEY.publickey()), "<SANITIZED RsaKey>")
    
    def test_client_options_keep_the_default_event_scrubber(self):
        # The `secret` dict is only filtered because of the SDK's default EventScrubber. Setting
        # send_default_pii, a custom event_scrubber, or data collection options in
        # sentry_client_options can turn that off without any visible change.
        client = sentry_sdk.Client(FAKE_DSN, **{**sentry_client_options(), "transport": CapturingTransport})
        self.assertFalse(client.options["send_default_pii"])
        self.assertIsInstance(client.options["event_scrubber"], EventScrubber)
        self.assertIn("secret", client.options["event_scrubber"].denylist)
    
    def test_decrypted_aes_key_is_filtered(self):
        # A wrong length key fails after the decrypted key is held in extract_aes_key's `secret`
        # dict, so that frame is in the report. The key and its base64 form must not appear anywhere,
        # and neither may the private key.
        aes_key = b"SECRETKEYMARKER_" * 2
        encryptor = DeviceEncryptor(aes_key=aes_key)
        event, serialized = self.capture(encryptor.encrypt_file(b"a"), DecryptionKeyInvalidError)
        
        self.assertEqual(self.get_frame(event, "extract_aes_key")["vars"]["secret"], "[Filtered]")
        self.assertNotIn("SECRETKEYMARKER", serialized)
        self.assertNotIn(encode_base64(aes_key).decode(), serialized)
        self.assertNotIn(str(RSA_KEY.d), serialized)
    
    def test_rsa_plaintext_that_fails_to_decode_is_not_reported(self):
        # Regression test. When the RSA plaintext is not valid base64, the decode error used to be
        # chained onto DecryptionKeyInvalidError. That put the RSA plaintext in the report through
        # the exception messages and through the local variables of decode_base64 and the stdlib
        # base64 functions, none of which are scrubbed. It is now raised `from None`.
        marker = b"SECRETMARKERabcde"  # 17 characters, an invalid base64 length
        file_data = key_line_from_rsa_plaintext(marker) + b"\n" + DeviceEncryptor().encrypt_line(b"a")
        event, serialized = self.capture(file_data, DecryptionKeyInvalidError)
        
        self.assertNotIn("SECRETMARKER", serialized)
        exceptions = event["exception"]["values"]
        self.assertEqual(len(exceptions), 1)  # no chained exceptions
        self.assertEqual(exceptions[0]["type"], "DecryptionKeyInvalidError")
        self.assertEqual(exceptions[0]["value"], "Invalid decryption key: Base64LengthException")
