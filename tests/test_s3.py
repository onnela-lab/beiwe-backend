        self.assertEqual(s3_file.sha1, hashlib.sha1(data).digest())
        self.assertEqual(s3_file.size_uncompressed, len(data))
        self.assertEqual(s3_file.size_compressed, len(compress(data)))
        self.assertEqual(s3_file.participant_id, self.default_participant.id)
        self.assertEqual(s3_file.study_id, self.default_study.id)
    
