class TestCompressionMemory(CommonTestCase):
    """ Memory regression tests for compress and decompress. Limits are set between the old and new
    measured peaks, so they fail if the old allocation pattern comes back. Measured on csv data:
    compress was 1.13x the input (now 0.41x), decompress was 2.1-3.3x the output depending on
    its size (now 2.0x). """
    
    def test_compress_does_not_allocate_an_input_sized_buffer(self):
        data = csv_data(200_000)
        _, peak = traced_peak(compress, data)
        self.assertLess(peak, 0.75 * len(data))
    
    def test_decompress_allocates_the_output_once_plus_one_copy(self):
        # Without a size hint the output grows in blocks of 32 KB, 64 KB, 256 KB, 1 MB, 4 MB, 8 MB...
        # just past a block boundary (~5.4 MB) most of the last block is wasted. ~5.8 MB of data
        # peaked at over 3x with the old code.
        data = csv_data(85_000)
        compressed = compress(data)
        _, peak = traced_peak(decompress, compressed)
        self.assertLess(peak, 2.05 * len(data))
